public abstract class Pengguna {
   
    private String id;
    private String nama;

    public Pengguna(String id, String nama) {
        this.id = id;
        this.nama = nama;
    }

    public String getId() { return id; }
    public String getNama() { return nama; }
    public abstract String peran();
}
    

